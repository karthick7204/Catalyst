import crypto from 'crypto';
import { prisma } from '../config/database.js';
import { config } from '../config/env.js';
import { logger } from '../config/logger.js';
import { postLinearComment, updateLinearIssueStatus } from '../linear/client.js';
import { createGitHubPullRequest } from '../github/client.js';
import { WorkspaceSandbox } from '../sandbox/workspace.js';

export class ApprovalService {
  /**
   * Generates a cryptographically secure approval token
   */
  static generateToken(): string {
    return crypto.randomBytes(32).toString('hex');
  }

  /**
   * Request human approval by posting an interactive comment on the Linear ticket
   */
  static async requestHumanApproval(params: {
    jobId: string;
    linearIssueId: string;
    linearIssueIdentifier: string;
    approvalToken: string;
    fixSummary: string;
    diff: string;
  }): Promise<void> {
    const { jobId, linearIssueId, linearIssueIdentifier, approvalToken, fixSummary, diff } = params;

    const approveUrl = `${config.APP_BASE_URL}/api/approvals/${jobId}?action=approve&token=${approvalToken}`;
    const rejectUrl = `${config.APP_BASE_URL}/api/approvals/${jobId}?action=reject&token=${approvalToken}`;

    const commentBody = `### 🤖 Catalyst AI Agent Fix Proposal for **${linearIssueIdentifier}**

${fixSummary}

<details>
<summary><b>🔍 View Git Diff (${diff.split('\n').length} lines)</b></summary>

\`\`\`diff
${diff.slice(0, 4000)}
${diff.length > 4000 ? '\n... (diff truncated for length)' : ''}
\`\`\`
</details>

---
### 🚦 Human-in-the-Loop Review
Please review the changes above before pushing to GitHub:

* **[✅ Approve & Open Pull Request](${approveUrl})**
* **[❌ Reject Fix](${rejectUrl})**
`;

    await postLinearComment(linearIssueId, commentBody);
    logger.info({ jobId, linearIssueIdentifier }, 'Approval comment posted to Linear ticket');
  }

  /**
   * Handle human decision (approve or reject)
   */
  static async handleDecision(params: {
    jobId: string;
    token: string;
    action: 'approve' | 'reject';
  }): Promise<{ success: boolean; message: string; prUrl?: string }> {
    const { jobId, token, action } = params;

    const job = await prisma.taskJob.findUnique({
      where: { id: jobId }
    });

    if (!job) {
      return { success: false, message: 'Task job not found' };
    }

    if (job.approvalToken !== token) {
      return { success: false, message: 'Invalid approval token' };
    }

    if (job.status !== 'AWAITING_APPROVAL') {
      return {
        success: false,
        message: `Task is already in status "${job.status}"`
      };
    }

    const sandbox = new WorkspaceSandbox(job.id, job.githubRepo, job.linearIssueIdentifier);

    if (action === 'reject') {
      await prisma.taskJob.update({
        where: { id: jobId },
        data: { status: 'REJECTED' }
      });

      await postLinearComment(
        job.linearIssueId,
        `❌ Fix proposal for **${job.linearIssueIdentifier}** was rejected by reviewer.`
      );

      await sandbox.cleanup();
      return { success: true, message: 'Fix was successfully rejected.' };
    }

    // Handle APPROVE
    try {
      await prisma.taskJob.update({
        where: { id: jobId },
        data: { status: 'APPROVED' }
      });

      // Commit changes in sandbox
      await sandbox.commitChanges(`fix: ${job.linearIssueTitle} (${job.linearIssueIdentifier})`);

      // Push branch to GitHub remote
      await sandbox.pushBranch();

      // Create GitHub Pull Request
      const [owner, repo] = job.githubRepo.split('/');
      const pr = await createGitHubPullRequest({
        owner,
        repo,
        title: `fix: ${job.linearIssueTitle} (${job.linearIssueIdentifier})`,
        head: sandbox.fixBranch,
        base: job.baseBranch || 'main',
        body: `## Summary
${job.fixSummary || 'Automated fix generated by Catalyst AI Agent.'}

Closes ${job.linearIssueIdentifier}
[Linear Ticket](${job.linearIssueUrl})
`
      });

      // Update database record
      await prisma.taskJob.update({
        where: { id: jobId },
        data: {
          status: 'PR_CREATED',
          prUrl: pr.prUrl
        }
      });

      // Update Linear issue status to "In Review"
      await updateLinearIssueStatus(job.linearIssueId, 'In Review');

      // Post comment on Linear issue with PR URL
      await postLinearComment(
        job.linearIssueId,
        `🚀 **Catalyst AI has opened Pull Request #${pr.prNumber}**: [${pr.prUrl}](${pr.prUrl})`
      );

      // Clean up sandbox
      await sandbox.cleanup();

      return {
        success: true,
        message: 'Pull request successfully created!',
        prUrl: pr.prUrl
      };
    } catch (err: any) {
      logger.error({ err, jobId }, 'Failed during PR creation after approval');
      await prisma.taskJob.update({
        where: { id: jobId },
        data: { status: 'FAILED', error: err.message }
      });
      return { success: false, message: `Error creating pull request: ${err.message}` };
    }
  }
}

